// Inatengeneza sql/tenant_template.sql kutoka database ya majaribio (structure tu, bila data).
// Run:  node scripts/generateTemplate.js            (inatumia hardware_pos)
//       node scripts/generateTemplate.js jina_la_db (database nyingine)
require('dotenv').config({ path: require('path').join(__dirname, '../.env') })
const fs = require('fs')
const path = require('path')
const mysql = require('mysql2/promise')

const SOURCE_DB = process.argv[2] || process.env.TEMPLATE_SOURCE_DB || 'hardware_pos'
const OUT_FILE = path.join(__dirname, '../sql/tenant_template.sql')

async function main() {
  const db = await mysql.createConnection({
    host: process.env.DB_HOST || 'localhost',
    user: process.env.DB_USER || 'root',
    password: process.env.DB_PASSWORD || '',
    port: process.env.DB_PORT || 3306,
    database: SOURCE_DB
  })

  const [rows] = await db.query("SHOW FULL TABLES WHERE Table_type = 'BASE TABLE'")
  const tables = rows.map((r) => Object.values(r)[0])

  let out = `-- Tenant template (structure only) from "${SOURCE_DB}"\n`
  out += '-- Generated by scripts/generateTemplate.js. Usihariri kwa mkono.\n\n'
  out += 'SET FOREIGN_KEY_CHECKS=0;\n\n'

  for (const t of tables) {
    const [[row]] = await db.query(`SHOW CREATE TABLE \`${t}\``)
    const ddl = row['Create Table']
      .replace(/ AUTO_INCREMENT=\d+/g, '')
      .replace(/^CREATE TABLE /, 'CREATE TABLE IF NOT EXISTS ')
    out += `${ddl};\n\n`
  }
  out += 'SET FOREIGN_KEY_CHECKS=1;\n'

  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true })
  fs.writeFileSync(OUT_FILE, out, 'utf8')

  // Thibitisho ya migrations 005 na 006
  const [perm] = await db.query("SHOW COLUMNS FROM users LIKE 'permissions'")
  console.log(`\nTables ${tables.length}: ${tables.join(', ')}`)
  console.log(`005 (users.permissions): ${perm.length ? 'IPO ✅' : 'HAIPO ❌ (provisioner itaiongeza yenyewe)'}`)
  console.log(`006 (user_roles table):  ${tables.includes('user_roles') ? 'IPO ✅' : 'HAIPO ❌ (provisioner itaitengeneza yenyewe)'}`)
  console.log(`\nImeandikwa: ${OUT_FILE}`)
  await db.end()
}

main().catch((e) => {
  console.error('FAILED:', e.message)
  process.exit(1)
})
